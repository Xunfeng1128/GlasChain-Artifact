package params

import (
	"fmt"
	"strings"
	"time"
)

// ValidateGARETConfig validates the shared execution adaptation. The runner
// creates the identity-only group catalog before starting any process.
func ValidateGARETConfig() error {
	if !UnifiedExecution || !UnifiedMetrics {
		return fmt.Errorf("GARET requires UnifiedExecution=true and UnifiedMetrics=true")
	}
	if err := ValidateUnifiedExecutionConfig(); err != nil {
		return err
	}
	if GARETGroupCount <= 0 || GARETGroupCount > 1000000 {
		return fmt.Errorf("GARETGroupCount must be in [1,1000000]")
	}
	if GARETSampleSeconds <= 0 || ReconfigTimeGap <= 0 || ReconfigTimeGap%GARETSampleSeconds != 0 {
		return fmt.Errorf("ReconfigTimeGap must be a positive multiple of GARETSampleSeconds")
	}
	if int64(ReconfigTimeGap) > int64((time.Duration(1<<63-1)/time.Second)/2) {
		return fmt.Errorf("GARET cycle duration overflows the history clock")
	}
	if strings.TrimSpace(GARETGroupCatalogFile) == "" {
		return fmt.Errorf("GARETGroupCatalogFile is required (generated by the experiment runner)")
	}
	if GARETReconfigurationTimeoutSeconds <= 0 || int64(GARETReconfigurationTimeoutSeconds) > int64(time.Duration(1<<63-1)/time.Second) {
		return fmt.Errorf("GARETReconfigurationTimeoutSeconds must be positive and fit a duration")
	}
	return nil
}
